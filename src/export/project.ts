import JSZip from 'jszip';
import { collectBlockNativeSources } from '../cbridge/nativeSources';
import { basename, kindOf, normalizePath } from '../core/paths';
import type { Project } from '../core/project';
import type { BlockGraph, FileKind, ProjectFile, ProjectSnapshot } from '../core/types';

const ALLOWED_EXTENSIONS = new Set(['lua', 'c', 'cpp', 'cc', 'cxx', 'h', 'hpp', 'hh', 'json', 'txt']);

export interface ProjectManifest {
  format: 'selene-forge';
  version: number;
  name: string;
  entry: string;
  installed: string[];
  openTabs: string[];
  activePath: string;
  savedAt: number;
  files: Array<{ path: string; kind: FileKind; locked: boolean; graph: BlockGraph | null }>;
}

function slug(value: string): string {
  return value.trim().toLowerCase().replace(/[^a-z0-9-_]+/g, '-').replace(/^-+|-+$/g, '') || 'selene-project';
}

export function downloadBlob(filename: string, blob: Blob): void {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export function downloadText(filename: string, text: string, mime = 'text/plain'): void {
  downloadBlob(filename, new Blob([text], { type: `${mime};charset=utf-8` }));
}

export function downloadFile(file: ProjectFile): void {
  const extension = file.path.split('.').pop() ?? 'txt';
  downloadText(basename(file.path), file.content, extension === 'json' ? 'application/json' : 'text/plain');
}

export function downloadGraph(file: ProjectFile): void {
  if (!file.graph) throw new Error('This file has no block graph yet.');
  const payload = {
    format: 'selene-forge-blocks',
    version: 1,
    path: file.path,
    name: basename(file.path),
    savedAt: Date.now(),
    graph: file.graph,
  };
  downloadText(`${basename(file.path).replace(/\.lua$/i, '')}.blocks.json`, JSON.stringify(payload, null, 2), 'application/json');
}

export function buildManifest(project: Project, entry: string): ProjectManifest {
  return {
    format: 'selene-forge',
    version: 1,
    name: project.name,
    entry,
    installed: [...project.installed],
    openTabs: [...project.openTabs],
    activePath: project.activePath,
    savedAt: Date.now(),
    files: project.list().map((file) => ({
      path: file.path,
      kind: file.kind,
      locked: file.locked,
      graph: file.graph,
    })),
  };
}

export async function buildProjectZip(project: Project, entry: string): Promise<Blob> {
  const zip = new JSZip();
  for (const file of project.list()) {
    zip.file(file.path, file.content);
  }
  zip.file('project.json', JSON.stringify(buildManifest(project, entry), null, 2));

  const nativeSources = collectBlockNativeSources(project.list());
  if (nativeSources.length > 0) {
    const header = `/* Generated by Selene Forge from visual C-bridge blocks.\n * Compile together with the project's native/*.c sources.\n */\n\n`;
    const body = nativeSources.map((source) => `/* ${source.path} */\n${source.source}`).join('\n');
    zip.file('native/selene-blocks.c', header + body);
  }

  return zip.generateAsync({ type: 'blob', compression: 'DEFLATE', compressionOptions: { level: 6 } });
}

export async function exportProjectZip(project: Project, entry: string): Promise<void> {
  const blob = await buildProjectZip(project, entry);
  downloadBlob(`${slug(project.name)}.zip`, blob);
}

/* ── Import ──────────────────────────────────────────────────────────────── */

export interface ImportedArchive {
  snapshot: ProjectSnapshot;
  manifestFound: boolean;
  skipped: string[];
}

function isManifest(value: unknown): value is ProjectManifest {
  return Boolean(value && typeof value === 'object' && (value as ProjectManifest).format === 'selene-forge');
}

export async function readArchive(file: File): Promise<ImportedArchive> {
  const zip = await JSZip.loadAsync(file);
  const skipped: string[] = [];
  let manifest: ProjectManifest | null = null;

  const manifestEntry = zip.file('project.json');
  if (manifestEntry) {
    try {
      const parsed = JSON.parse(await manifestEntry.async('string')) as unknown;
      if (isManifest(parsed)) manifest = parsed;
    } catch {
      skipped.push('project.json (invalid JSON)');
    }
  }

  const files: ProjectFile[] = [];
  let sequence = 0;
  for (const [path, entry] of Object.entries(zip.files)) {
    if (entry.dir) continue;
    if (path === 'project.json') continue;
    if (path === 'native/selene-blocks.c') continue;
    const extension = path.split('.').pop()?.toLowerCase() ?? '';
    if (!ALLOWED_EXTENSIONS.has(extension)) {
      skipped.push(path);
      continue;
    }
    let normalized: string;
    try {
      normalized = normalizePath(path);
    } catch {
      skipped.push(path);
      continue;
    }
    const content = await entry.async('string');
    const meta = manifest?.files.find((candidate) => candidate.path === normalized);
    sequence += 1;
    files.push({
      id: `import-${Date.now().toString(36)}-${sequence}`,
      path: normalized,
      content,
      kind: meta?.kind ?? kindOf(normalized),
      graph: meta?.graph ?? null,
      locked: meta?.locked ?? (kindOf(normalized) === 'lua' ? true : false),
    });
  }

  const folders = new Set<string>();
  for (const file of files) {
    const parts = file.path.split('/');
    for (let index = 1; index < parts.length; index += 1) folders.add(parts.slice(0, index).join('/'));
  }

  const activePath = manifest?.activePath && files.some((file) => file.path === manifest.activePath)
    ? manifest.activePath
    : files.find((file) => file.path === manifest?.entry)?.path ?? files[0]?.path ?? '';

  const snapshot: ProjectSnapshot = {
    version: 1,
    name: manifest?.name || file.name.replace(/\.zip$/i, '') || 'imported-project',
    files,
    folders: [...folders],
    openTabs: (manifest?.openTabs ?? []).filter((path) => files.some((entry) => entry.path === path)),
    activePath,
    installed: manifest?.installed ?? [],
    savedAt: Date.now(),
  };
  if (snapshot.activePath && !snapshot.openTabs.includes(snapshot.activePath)) snapshot.openTabs.unshift(snapshot.activePath);

  return { snapshot, manifestFound: Boolean(manifest), skipped };
}

export interface ParsedFileImport {
  kind: 'graph' | 'manifest';
  graph?: BlockGraph;
  path?: string;
  snapshot?: ProjectSnapshot;
}

/** Parse a standalone `.json` that may be a block graph or a workspace manifest. */
export function parseJsonImport(text: string): ParsedFileImport {
  const parsed = JSON.parse(text) as Record<string, unknown>;
  if (isManifest(parsed) && Array.isArray(parsed.files)) {
    const snapshot: ProjectSnapshot = {
      version: 1,
      name: parsed.name || 'imported-project',
      files: (parsed.files as Array<Record<string, unknown>>).map((file, index) => ({
        id: `json-${index}`,
        path: String(file.path ?? `file-${index}.lua`),
        content: String(file.content ?? ''),
        kind: (file.kind as FileKind) ?? kindOf(String(file.path ?? '')),
        graph: (file.graph as BlockGraph) ?? null,
        locked: Boolean(file.locked),
      })),
      folders: [],
      openTabs: [],
      activePath: '',
      installed: parsed.installed ?? [],
      savedAt: Date.now(),
    };
    return { kind: 'manifest', snapshot };
  }
  if (parsed.format === 'selene-forge-blocks' && parsed.graph) {
    return { kind: 'graph', graph: parsed.graph as BlockGraph, path: String(parsed.path ?? '') };
  }
  if (parsed.blocks) {
    return { kind: 'graph', graph: parsed as BlockGraph };
  }
  throw new Error('Unrecognised JSON: expected a block graph or a Selene Forge project manifest.');
}
